// The GTK surface that M7's `insert_widgets` builds its page from, checked
// against the GTK version this crate was generated from.
//
// No test here constructs a widget. This is deliberate, not an oversight.
// GTK 3 refuses: `gtk_grid_new()` reaches `GtkWidget`'s instance init, which
// needs a `GtkStyleContext`. Without a display connection, that aborts the
// process with "Can't create a GtkStyleContext without a display
// connection" (checked on a machine with no display). So a real Evolution
// session is the only place to exercise the page itself (M9's Xvfb tier
// seeds a pre-built `.source` file instead of driving the page). This file
// checks the part that a machine without a display can check. That part
// also fails silently otherwise:
//
// - The entry points exist in the libraries this crate links. A missing
//   entry point becomes an `undefined symbol` the moment Evolution dlopens
//   the module: a feature that disappears, with only a line in a log
//   nobody reads.
// - The types those entry points take are the classes this crate assumes.
//   Those classes stand in the inheritance relations that make the pointer
//   casts between them legitimate. GTK's C API takes a `GtkGrid *` in one
//   place and a `GtkWidget *` in another, for the same object. On this
//   side of the ABI, those are separate opaque types, so the code must
//   write down each cast explicitly.
// - The opaque types stayed opaque. A handle with a nonzero size means
//   somebody generated a layout for that struct. A wrong layout for a
//   `GtkWidget` corrupts a live widget.

use evo_sys::*;
use std::mem::size_of;
use std::sync::OnceLock;

/// Every widget class this crate names, with the name GTK registers it under.
const CLASSES: &[(&str, unsafe extern "C" fn() -> GType)] = &[
    ("GtkWidget", gtk_widget_get_type),
    ("GtkContainer", gtk_container_get_type),
    ("GtkBox", gtk_box_get_type),
    ("GtkGrid", gtk_grid_get_type),
    ("GtkLabel", gtk_label_get_type),
    ("GtkEntry", gtk_entry_get_type),
    ("GtkCheckButton", gtk_check_button_get_type),
    ("GtkComboBoxText", gtk_combo_box_text_get_type),
    ("GtkScrolledWindow", gtk_scrolled_window_get_type),
    ("GtkTextView", gtk_text_view_get_type),
    // GtkTextBuffer is not a widget. The is-a test exempts it, but this
    // list names it so the same once-guarded registration and name check
    // cover it.
    ("GtkTextBuffer", gtk_text_buffer_get_type),
];

/// This function registers the classes exactly once. On GTK 3, registering
/// them more than once is not safe. The code must arrange this itself.
///
/// `gtk_container_get_type()` is hand-written, not generated by the
/// `G_DEFINE_TYPE` macro. Its once-guard is a plain
/// `static GType container_type = 0;`. The code tests and sets this guard
/// with no `g_once_init_enter` around it. If two threads call the function
/// at the same moment, both threads see a zero value. Both threads then
/// register the type. This file caught that failure the first time. The
/// error was `cannot register existing type 'GtkContainer'`, followed by
/// an `<invalid>` type whose `get_type` then returns 0 forever. Two
/// `#[test]` functions caused this by touching the type system in
/// parallel. The default test harness runs tests on separate threads.
///
/// This is GTK behaving as documented: callers must call GTK 3 from one
/// thread only. It is not a bug to route around. Instead, the tests
/// change. Every test reaches the type system through this function.
/// `OnceLock` makes the first caller register every class in [`CLASSES`],
/// while the other callers wait.
fn classes() -> &'static Vec<(&'static str, GType)> {
    static CLASS_TYPES: OnceLock<Vec<(&'static str, GType)>> = OnceLock::new();
    CLASS_TYPES.get_or_init(|| {
        CLASSES
            .iter()
            .map(|(name, get_type)| (*name, unsafe { get_type() }))
            .collect()
    })
}

/// One of the classes, by the name this file knows it under.
fn class(wanted: &str) -> GType {
    classes()
        .iter()
        .find(|(name, _)| *name == wanted)
        .map(|(_, gtype)| *gtype)
        .unwrap_or_else(|| panic!("{wanted} is not one of the classes this crate names"))
}

fn type_name(gtype: GType) -> String {
    unsafe {
        let name = g_type_name(gtype);
        assert!(!name.is_null(), "g_type_name returned NULL for {gtype}");
        std::ffi::CStr::from_ptr(name)
            .to_string_lossy()
            .into_owned()
    }
}

/// This test confirms the classes are the ones this crate assumes. It
/// asserts by name, not by numeric `GType`, which is an address that
/// differs every run.
#[test]
fn the_widget_types_are_the_classes_this_crate_names() {
    for (expected, gtype) in classes() {
        assert_ne!(
            *gtype, 0,
            "{expected}: get_type() returned an invalid GType"
        );
        assert_eq!(
            type_name(*gtype).as_str(),
            *expected,
            "the type behind {expected}'s getter is registered under another name"
        );
    }
}

/// What makes the casts between these classes valid.
///
/// `gtk_grid_new` returns a `GtkWidget *`. `gtk_grid_attach` requires that
/// pointer as a `GtkGrid *`. `gtk_grid_attach`'s child argument is also a
/// `GtkWidget *`, and that argument will be a label or an entry. These are
/// three casts. Each cast is valid only because GTK's type system relates
/// the classes this way. If GTK ever reparented one of these classes (for
/// example, GtkLabel's real parent on GTK 3.24 is the deprecated
/// `GtkMisc`), the cast crossing that changed edge starts reading the
/// wrong offsets.
#[test]
fn the_casts_the_widget_calls_require_are_upcasts_gtk_agrees_with() {
    let widget = class("GtkWidget");
    let container = class("GtkContainer");
    for (name, gtype) in classes() {
        if *name == "GtkTextBuffer" {
            // GtkTextBuffer is the one plain GObject in this list. Code
            // reaches it only through `gtk_text_view_get_buffer` and the
            // `text` property.
            continue;
        }
        assert_eq!(
            unsafe { g_type_is_a(*gtype, widget) },
            GTRUE,
            "{name} is no longer a GtkWidget: every call here that takes a GtkWidget * would be handed one that is not"
        );
    }
    for name in ["GtkBox", "GtkGrid"] {
        assert_eq!(
            unsafe { g_type_is_a(class(name), container) },
            GTRUE,
            "{name} is no longer a GtkContainer, so it is no longer a thing children are added to"
        );
    }
}

/// The handles stay opaque handles. Nothing in this crate knows the layout
/// of a `GtkWidget`, and this assertion keeps it that way. A nonzero size
/// here means something generated a layout for a GTK class struct.
/// `build.rs` refuses to take on that binding surface. Unlike the EDS
/// structs `tests/layout.rs` checks, nothing cross-checks a GTK layout
/// against `g_type_query`.
#[test]
fn the_widget_handles_carry_no_layout() {
    assert_eq!(size_of::<GtkWidget>(), 0, "GtkWidget is no longer opaque");
    assert_eq!(size_of::<GtkBox>(), 0, "GtkBox is no longer opaque");
    assert_eq!(size_of::<GtkGrid>(), 0, "GtkGrid is no longer opaque");
    assert_eq!(size_of::<GtkLabel>(), 0, "GtkLabel is no longer opaque");
    assert_eq!(size_of::<GtkEntry>(), 0, "GtkEntry is no longer opaque");
    assert_eq!(
        size_of::<GtkComboBoxText>(),
        0,
        "GtkComboBoxText is no longer opaque"
    );
    assert_eq!(
        size_of::<GtkTextView>(),
        0,
        "GtkTextView is no longer opaque"
    );
    assert_eq!(
        size_of::<GtkTextBuffer>(),
        0,
        "GtkTextBuffer is no longer opaque"
    );
    assert_eq!(
        size_of::<GtkContainer>(),
        0,
        "GtkContainer is no longer opaque"
    );
    assert_eq!(size_of::<EDateEdit>(), 0, "EDateEdit is no longer opaque");
}

