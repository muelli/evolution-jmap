//! Turns [`crate::filters::rules::Rule`]s into Sieve script source, and back.
//!
//! The managed script format is plain text with the rules encoded as
//! comments: a two-line header names the format, then each rule is one
//! `# rule <json>` comment line followed by the Sieve the rule generates.
//! [`load`] trusts a script only if generating it again from the parsed
//! rules reproduces the server's bytes exactly; otherwise the caller shows
//! the script as plain text, since someone edited it outside Evolution.
//!
//! This module has no FFI and is unit-tested directly with exact expected
//! script text.

use std::collections::BTreeSet;

use super::rules::{Action, Combine, Condition, Field, Folder, Op, Rule};

/// The first line of a script this crate manages.
pub const HEADER_LINE_1: &str =
    "# Generated by Evolution (JMAP). Edit it in Evolution's account editor.";
/// The second line of a script this crate manages: the format version.
pub const HEADER_LINE_2: &str = "# evolution-jmap-rules 1";

const RULE_PREFIX: &str = "# rule ";

/// Generates the full Sieve script text for a list of rules.
///
/// `has_mailboxid` is whether the server's Sieve capability lists the
/// `mailboxid` extension (RFC 9042): when true, `MoveTo`/`CopyTo` address
/// the folder by id as well as by name.
pub fn generate_script(rules: &[Rule], has_mailboxid: bool) -> String {
    let mut out = String::new();
    out.push_str(HEADER_LINE_1);
    out.push('\n');
    out.push_str(HEADER_LINE_2);
    out.push('\n');
    let extensions = required_extensions(rules, has_mailboxid);
    if !extensions.is_empty() {
        let list = extensions
            .iter()
            .map(|extension| format!("\"{extension}\""))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("require [{list}];\n"));
    }
    for rule in rules {
        out.push('\n');
        out.push_str(RULE_PREFIX);
        out.push_str(&serde_json::to_string(rule).expect("a Rule always serializes"));
        out.push('\n');
        if rule.enabled {
            out.push_str(&generate_rule_body(rule, has_mailboxid));
        }
    }
    out
}

/// Parses the rules a script's `# rule <json>` comment lines encode.
///
/// Returns `None` if the first two lines are not this crate's header: the
/// script is not one this crate wrote. A rule line with invalid JSON is
/// also `None`, since a script this crate wrote never has one.
pub fn parse_script(text: &str) -> Option<Vec<Rule>> {
    let mut lines = text.lines();
    if lines.next()? != HEADER_LINE_1 {
        return None;
    }
    if lines.next()? != HEADER_LINE_2 {
        return None;
    }
    let mut rules = Vec::new();
    for line in lines {
        if let Some(json) = line.strip_prefix(RULE_PREFIX) {
            rules.push(serde_json::from_str(json).ok()?);
        }
    }
    Some(rules)
}

/// Loads the rules a server-stored script encodes, in rules mode (D5).
///
/// Parses the script, then generates it again from the parsed rules and
/// compares the result with `server_text` byte for byte. Returns the rules
/// only on an exact match; otherwise `None`, meaning the caller shows the
/// script as plain text, since it was not written by this crate or was
/// changed since.
pub fn load(server_text: &str, has_mailboxid: bool) -> Option<Vec<Rule>> {
    let rules = parse_script(server_text)?;
    (generate_script(&rules, has_mailboxid) == server_text).then_some(rules)
}

/// The Sieve extensions an enabled rule's actions need, sorted.
fn required_extensions(rules: &[Rule], has_mailboxid: bool) -> BTreeSet<&'static str> {
    let mut extensions = BTreeSet::new();
    for rule in rules.iter().filter(|rule| rule.enabled) {
        for action in &rule.actions {
            match action {
                Action::MoveTo(_) => {
                    extensions.insert("fileinto");
                    if has_mailboxid {
                        extensions.insert("mailboxid");
                    }
                }
                Action::CopyTo(_) => {
                    extensions.insert("fileinto");
                    extensions.insert("copy");
                    if has_mailboxid {
                        extensions.insert("mailboxid");
                    }
                }
                Action::MarkRead | Action::Flag => {
                    extensions.insert("imap4flags");
                }
                Action::Redirect { keep: true, .. } => {
                    extensions.insert("copy");
                }
                Action::Redirect { keep: false, .. } | Action::Discard => {}
            }
        }
    }
    extensions
}

/// The `if <test> { <actions> }` block an enabled rule generates.
fn generate_rule_body(rule: &Rule, has_mailboxid: bool) -> String {
    let mut body = format!("if {} {{\n", test_expr(rule));
    for action in &rule.actions {
        body.push_str("    ");
        body.push_str(&generate_action(action, has_mailboxid));
        body.push('\n');
    }
    if rule.stop {
        body.push_str("    stop;\n");
    }
    body.push_str("}\n");
    body
}

/// The Sieve test expression for a rule's conditions, combined per D6/D7.
fn test_expr(rule: &Rule) -> String {
    match rule.conditions.as_slice() {
        [] => "true".to_owned(),
        [only] => condition_test(only),
        many => {
            let verb = match rule.combine {
                Combine::All => "allof",
                Combine::Any => "anyof",
            };
            let tests: Vec<String> = many.iter().map(condition_test).collect();
            format!("{verb}({})", tests.join(", "))
        }
    }
}

/// The Sieve test expression for one condition.
fn condition_test(condition: &Condition) -> String {
    if let Field::Size = condition.field {
        let tag = match condition.op {
            Op::Over => ":over",
            Op::Under => ":under",
            _ => unreachable!("Rule::validate rejects Size with anything but Over/Under"),
        };
        return format!("size {tag} {}K", condition.value);
    }
    let header_arg = match &condition.field {
        Field::From => "\"from\"".to_owned(),
        Field::To => "\"to\"".to_owned(),
        Field::Cc => "\"cc\"".to_owned(),
        Field::ToOrCc => "[\"to\",\"cc\"]".to_owned(),
        Field::Subject => "\"subject\"".to_owned(),
        Field::Header(name) => format!("\"{}\"", escape(name)),
        Field::Size => unreachable!("handled above"),
    };
    let (tag, negate) = match condition.op {
        Op::Contains => (":contains", false),
        Op::NotContains => (":contains", true),
        Op::Is => (":is", false),
        Op::Matches => (":matches", false),
        Op::Over | Op::Under => {
            unreachable!("Rule::validate rejects Over/Under with anything but Size")
        }
    };
    let value = format!("\"{}\"", escape(&condition.value));
    let test = match condition.field {
        Field::Subject | Field::Header(_) => format!("header {tag} {header_arg} {value}"),
        _ => format!("address :all {tag} {header_arg} {value}"),
    };
    if negate { format!("not {test}") } else { test }
}

/// The Sieve statement for one action.
fn generate_action(action: &Action, has_mailboxid: bool) -> String {
    match action {
        Action::MoveTo(folder) => format!("{};", fileinto(folder, false, has_mailboxid)),
        Action::CopyTo(folder) => format!("{};", fileinto(folder, true, has_mailboxid)),
        Action::MarkRead => "addflag \"\\\\Seen\";".to_owned(),
        Action::Flag => "addflag \"\\\\Flagged\";".to_owned(),
        Action::Redirect { address, keep } => {
            if *keep {
                format!("redirect :copy \"{}\";", escape(address))
            } else {
                format!("redirect \"{}\";", escape(address))
            }
        }
        Action::Discard => "discard;".to_owned(),
    }
}

/// The `fileinto` statement body (no trailing `;`) for `MoveTo`/`CopyTo`.
fn fileinto(folder: &Folder, copy: bool, has_mailboxid: bool) -> String {
    let mut tags = String::new();
    if copy {
        tags.push_str(":copy ");
    }
    if has_mailboxid {
        tags.push_str(&format!(":mailboxid \"{}\" ", escape(&folder.id)));
    }
    format!("fileinto {tags}\"{}\"", escape(&folder.name))
}

/// Escapes `\` and `"` for a Sieve quoted string. Nothing else changes.
fn escape(value: &str) -> String {
    value.replace('\\', "\\\\").replace('"', "\\\"")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rule(name: &str, conditions: Vec<Condition>, actions: Vec<Action>) -> Rule {
        Rule {
            name: name.to_owned(),
            enabled: true,
            combine: Combine::All,
            conditions,
            actions,
            stop: false,
        }
    }

    #[test]
    fn empty_script_has_only_the_header() {
        let expected = "# Generated by Evolution (JMAP). Edit it in Evolution's account editor.\n\
             # evolution-jmap-rules 1\n";
        assert_eq!(generate_script(&[], false), expected);
    }

    #[test]
    fn subject_contains_move_to_with_stop_no_mailboxid() {
        let mut r = rule(
            "Invoices",
            vec![Condition {
                field: Field::Subject,
                op: Op::Contains,
                value: "invoice".to_owned(),
            }],
            vec![Action::MoveTo(Folder {
                id: "M1".to_owned(),
                name: "Invoices".to_owned(),
            })],
        );
        r.stop = true;
        let expected = "# Generated by Evolution (JMAP). Edit it in Evolution's account editor.\n\
            # evolution-jmap-rules 1\n\
            require [\"fileinto\"];\n\
            \n\
            # rule {\"name\":\"Invoices\",\"enabled\":true,\"combine\":\"All\",\"conditions\":\
            [{\"field\":\"Subject\",\"op\":\"Contains\",\"value\":\"invoice\"}],\"actions\":\
            [{\"MoveTo\":{\"id\":\"M1\",\"name\":\"Invoices\"}}],\"stop\":true}\n\
            if header :contains \"subject\" \"invoice\" {\n\
            \x20\x20\x20\x20fileinto \"Invoices\";\n\
            \x20\x20\x20\x20stop;\n\
            }\n";
        assert_eq!(generate_script(&[r], false), expected);
    }

    #[test]
    fn move_to_with_mailboxid_adds_the_tag_and_the_extension() {
        let r = rule(
            "Invoices",
            vec![],
            vec![Action::MoveTo(Folder {
                id: "M1".to_owned(),
                name: "Invoices".to_owned(),
            })],
        );
        let script = generate_script(&[r], true);
        assert!(script.contains("require [\"fileinto\", \"mailboxid\"];\n"));
        assert!(script.contains("if true {\n    fileinto :mailboxid \"M1\" \"Invoices\";\n}\n"));
    }

    #[test]
    fn copy_to_requires_copy_and_fileinto() {
        let r = rule(
            "Archive",
            vec![],
            vec![Action::CopyTo(Folder {
                id: "M2".to_owned(),
                name: "Archive".to_owned(),
            })],
        );
        let script = generate_script(&[r], false);
        assert!(script.contains("require [\"copy\", \"fileinto\"];\n"));
        assert!(script.contains("if true {\n    fileinto :copy \"Archive\";\n}\n"));
    }

    #[test]
    fn mark_read_and_flag_require_imap4flags() {
        let r = rule("Flagged", vec![], vec![Action::MarkRead, Action::Flag]);
        let script = generate_script(&[r], false);
        assert!(script.contains("require [\"imap4flags\"];\n"));
        assert!(
            script.contains(
                "if true {\n    addflag \"\\\\Seen\";\n    addflag \"\\\\Flagged\";\n}\n"
            )
        );
    }

    #[test]
    fn redirect_without_keep_has_no_copy_tag_or_extension() {
        let r = rule(
            "Forward",
            vec![],
            vec![Action::Redirect {
                address: "person@example.com".to_owned(),
                keep: false,
            }],
        );
        let script = generate_script(&[r], false);
        assert!(!script.contains("require"));
        assert!(script.contains("redirect \"person@example.com\";"));
    }

    #[test]
    fn redirect_with_keep_requires_copy() {
        let r = rule(
            "Forward",
            vec![],
            vec![Action::Redirect {
                address: "person@example.com".to_owned(),
                keep: true,
            }],
        );
        let script = generate_script(&[r], false);
        assert!(script.contains("require [\"copy\"];\n"));
        assert!(script.contains("redirect :copy \"person@example.com\";"));
    }

    #[test]
    fn discard_needs_no_extension() {
        let r = rule("Drop", vec![], vec![Action::Discard]);
        let script = generate_script(&[r], false);
        assert!(!script.contains("require"));
        assert!(script.contains("discard;"));
    }

    #[test]
    fn from_to_cc_use_address_test() {
        let from = condition_test(&Condition {
            field: Field::From,
            op: Op::Contains,
            value: "x".to_owned(),
        });
        assert_eq!(from, "address :all :contains \"from\" \"x\"");
        let to = condition_test(&Condition {
            field: Field::To,
            op: Op::Is,
            value: "x".to_owned(),
        });
        assert_eq!(to, "address :all :is \"to\" \"x\"");
        let cc = condition_test(&Condition {
            field: Field::Cc,
            op: Op::Matches,
            value: "*@x.com".to_owned(),
        });
        assert_eq!(cc, "address :all :matches \"cc\" \"*@x.com\"");
    }

    #[test]
    fn to_or_cc_uses_a_header_list() {
        let test = condition_test(&Condition {
            field: Field::ToOrCc,
            op: Op::Contains,
            value: "x".to_owned(),
        });
        assert_eq!(test, "address :all :contains [\"to\",\"cc\"] \"x\"");
    }

    #[test]
    fn not_contains_wraps_the_contains_test_in_not() {
        let test = condition_test(&Condition {
            field: Field::Subject,
            op: Op::NotContains,
            value: "spam".to_owned(),
        });
        assert_eq!(test, "not header :contains \"subject\" \"spam\"");
    }

    #[test]
    fn custom_header_uses_a_header_test() {
        let test = condition_test(&Condition {
            field: Field::Header("X-Spam-Score".to_owned()),
            op: Op::Is,
            value: "9".to_owned(),
        });
        assert_eq!(test, "header :is \"X-Spam-Score\" \"9\"");
    }

    #[test]
    fn size_over_writes_kilobytes() {
        let test = condition_test(&Condition {
            field: Field::Size,
            op: Op::Over,
            value: "100".to_owned(),
        });
        assert_eq!(test, "size :over 100K");
    }

    #[test]
    fn size_under_writes_kilobytes() {
        let test = condition_test(&Condition {
            field: Field::Size,
            op: Op::Under,
            value: "5".to_owned(),
        });
        assert_eq!(test, "size :under 5K");
    }

    #[test]
    fn escaping_doubles_backslash_and_quote() {
        let test = condition_test(&Condition {
            field: Field::Subject,
            op: Op::Contains,
            value: "a \"quote\" and a \\backslash".to_owned(),
        });
        assert_eq!(
            test,
            "header :contains \"subject\" \"a \\\"quote\\\" and a \\\\backslash\""
        );
    }

    #[test]
    fn several_conditions_combine_with_allof_or_anyof() {
        let mut r = rule(
            "Both",
            vec![
                Condition {
                    field: Field::Subject,
                    op: Op::Contains,
                    value: "a".to_owned(),
                },
                Condition {
                    field: Field::From,
                    op: Op::Contains,
                    value: "b".to_owned(),
                },
            ],
            vec![Action::Discard],
        );
        assert!(generate_script(&[r.clone()], false).contains(
            "allof(header :contains \"subject\" \"a\", address :all :contains \"from\" \"b\")"
        ));
        r.combine = Combine::Any;
        assert!(generate_script(&[r], false).contains(
            "anyof(header :contains \"subject\" \"a\", address :all :contains \"from\" \"b\")"
        ));
    }

    #[test]
    fn no_conditions_matches_every_message() {
        let r = rule("Catch all", vec![], vec![Action::Discard]);
        assert!(generate_script(&[r], false).contains("if true {\n"));
    }

    #[test]
    fn a_disabled_rule_has_only_its_comment_line() {
        let mut r = rule("Off", vec![], vec![Action::Discard]);
        r.enabled = false;
        let script = generate_script(&[r], false);
        assert!(script.contains("# rule {\"name\":\"Off\""));
        assert!(!script.contains("discard"));
        assert!(!script.contains("if "));
    }

    #[test]
    fn round_trips_through_generate_and_parse() {
        let rules = vec![
            rule(
                "Invoices",
                vec![Condition {
                    field: Field::Subject,
                    op: Op::Contains,
                    value: "invoice".to_owned(),
                }],
                vec![Action::MoveTo(Folder {
                    id: "M1".to_owned(),
                    name: "Invoices".to_owned(),
                })],
            ),
            {
                let mut off = rule("Off", vec![], vec![Action::Discard]);
                off.enabled = false;
                off
            },
        ];
        let script = generate_script(&rules, true);
        assert_eq!(parse_script(&script).as_ref(), Some(&rules));
        assert_eq!(load(&script, true), Some(rules));
    }

    #[test]
    fn a_script_without_the_header_does_not_parse() {
        assert_eq!(parse_script("require [\"fileinto\"];\n"), None);
    }

    #[test]
    fn a_hand_edited_script_fails_the_round_trip() {
        let r = rule("Invoices", vec![], vec![Action::Discard]);
        let mut script = generate_script(&[r], false);
        script.push_str("# a line someone added by hand\n");
        // The `# rule` lines still parse...
        assert!(parse_script(&script).is_some());
        // ...but regenerating does not reproduce the edited bytes.
        assert_eq!(load(&script, false), None);
    }
}
