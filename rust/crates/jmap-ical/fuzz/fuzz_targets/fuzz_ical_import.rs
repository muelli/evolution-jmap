#![no_main]

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    if let Ok(text) = std::str::from_utf8(data) {
        if let Ok(event) = jmap_ical::ical_to_event(text) {
            let _ = jmap_ical::event_to_ical(&event);
        }
    }
});
